let currentLang = 'ru';

const LANG_STORAGE_KEY = 'av-portfolio-lang';

/* =============================================================
   ПУБЛИЧНЫЕ МЕТОДЫ
   ============================================================= */

/**
 * Получить текущий язык
 */
export function getLang() {
    return currentLang;
}

/**
 * Получить перевод по ключу
 */
export function t(key) {
    return translations[currentLang]?.[key] || key;
}

/**
 * Сменить язык
 */
export function setLang(lang) {
    if (!translations[lang]) return;
    currentLang = lang;
    try {
        localStorage.setItem(LANG_STORAGE_KEY, lang);
    } catch (e) { /* ignore */ }
}

/**
 * Переключить язык туда-обратно
 */
export function toggleLang() {
    setLang(currentLang === 'ru' ? 'en' : 'ru');
    return currentLang;
}

/**
 * Восстановить язык из localStorage (при загрузке страницы)
 */
export function restoreLang() {
    try {
        const saved = localStorage.getItem(LANG_STORAGE_KEY);
        if (saved && translations[saved]) {
            currentLang = saved;
        } else {
            // Автоопределение по браузеру
            const navLang = (navigator.language || 'ru').toLowerCase();
            currentLang = navLang.startsWith('ru') ? 'ru' : 'en';
        }
    } catch (e) {
        currentLang = 'ru';
    }
    return currentLang;
}

/**
 * Применить переводы ко всем [data-i18n] элементам в DOM
 */
export function applyTranslations() {
    document.documentElement.lang = currentLang;

    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.dataset.i18n;
        const value = translations[currentLang][key];
        if (value !== undefined) {
            el.textContent = value;
        }
    });

    // Кнопки языка
    const langLabel = currentLang === 'ru' ? 'EN' : 'RU';
    document.querySelectorAll('.nav__lang, .menu__lang').forEach(btn => {
        btn.textContent = langLabel;
        btn.setAttribute(
            'aria-label',
            currentLang === 'ru' ? 'Switch to English' : 'Переключить на русский'
        );
    });
}